package com.app.knowledge.model;

/**
 * 分块策略。两种都是纯本地字符串处理，无外部依赖。
 *
 * 语义分块第一版不做：它要对每个候选切点两侧算 Embedding 相似度，调用量是普通分块
 * 的数倍，而收益需要有评测体系（Phase 4）才能量化——届时能用数据说明它值不值得。
 */
public enum ChunkStrategy {

    /** 按字符数硬切，相邻分块重叠 {@code overlap} 个字符。行为完全可预测，作为兜底。 */
    FIXED_SIZE,

    /**
     * 按分隔符优先级递归切分：先用最高优先级分隔符切，超长片段再用下一级切，最终仍
     * 超长的硬切。适合有段落/句子结构的文档，是默认策略。
     */
    RECURSIVE
}
